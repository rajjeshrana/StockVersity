# =========================================================
# MARKET REGIME
# =========================================================

class MarketRegime(str, Enum):
    """
    Broad trading environment.
    """

    STRONG_TREND = "STRONG_TREND"

    TRENDING = "TRENDING"

    RANGE_BOUND = "RANGE_BOUND"

    HIGH_VOLATILITY = "HIGH_VOLATILITY"

    LOW_VOLATILITY = "LOW_VOLATILITY"

    UNCERTAIN = "UNCERTAIN"


# =========================================================
# MARKET BIAS
# =========================================================

class MarketBias(str, Enum):

    STRONG_BULLISH = "STRONG_BULLISH"

    BULLISH = "BULLISH"

    NEUTRAL = "NEUTRAL"

    BEARISH = "BEARISH"

    STRONG_BEARISH = "STRONG_BEARISH"


# =========================================================
# ANALYSIS RESULT
# =========================================================

@dataclass(slots=True)
class MarketContextResult:
    """
    Result generated by MarketContextAnalyzer.
    """

    trend: MarketTrend = MarketTrend.SIDEWAYS

    bias: MarketBias = MarketBias.NEUTRAL

    regime: MarketRegime = MarketRegime.UNCERTAIN

    strength: float = 0.0

    bullish_score: float = 0.0

    bearish_score: float = 0.0

    long_allowed: bool = True

    short_allowed: bool = True

    volatility_score: float = 0.0

    breadth_score: float = 0.0

    index_score: float = 0.0

    reason: str = ""

    # =====================================================
    # EXPORT
    # =====================================================

    def to_dict(
        self,
    ) -> Dict[str, Any]:

        return {

            "trend":
                self.trend.value,

            "bias":
                self.bias.value,

            "regime":
                self.regime.value,

            "strength":
                self.strength,

            "bullish_score":
                self.bullish_score,

            "bearish_score":
                self.bearish_score,

            "long_allowed":
                self.long_allowed,

            "short_allowed":
                self.short_allowed,

            "volatility_score":
                self.volatility_score,

            "breadth_score":
                self.breadth_score,

            "index_score":
                self.index_score,

            "reason":
                self.reason,
        }


# =========================================================
# MARKET CONTEXT ANALYZER
# =========================================================

class MarketContextAnalyzer:
    """
    Analyze ScannerContext and determine the current
    market environment.
    """

    # =====================================================
    # INDEX SCORE
    # =====================================================

    @staticmethod
    def _index_direction_score(
        index: Optional[IndexState],
    ) -> float:
        """
        Return directional score from -100 to +100.
        """

        if index is None:
            return 0.0

        score = 0.0

        # ---------------------------------------------
        # INDEX CHANGE
        # ---------------------------------------------

        if index.change_percent >= 1.0:

            score += 30.0

        elif index.change_percent >= 0.50:

            score += 20.0

        elif index.change_percent > 0:

            score += 10.0

        elif index.change_percent <= -1.0:

            score -= 30.0

        elif index.change_percent <= -0.50:

            score -= 20.0

        elif index.change_percent < 0:

            score -= 10.0

        # ---------------------------------------------
        # TREND
        # ---------------------------------------------

        if index.trend == MarketTrend.STRONG_BULLISH:

            score += 35.0

        elif index.trend == MarketTrend.BULLISH:

            score += 25.0

        elif index.trend == MarketTrend.STRONG_BEARISH:

            score -= 35.0

        elif index.trend == MarketTrend.BEARISH:

            score -= 25.0

        # ---------------------------------------------
        # EMA STRUCTURE
        # ---------------------------------------------

        price = index.last_price

        if price > 0:

            if (
                index.ema20 > 0
                and price > index.ema20
            ):
                score += 5.0

            elif (
                index.ema20 > 0
                and price < index.ema20
            ):
                score -= 5.0

            if (
                index.ema50 > 0
                and price > index.ema50
            ):
                score += 5.0

            elif (
                index.ema50 > 0
                and price < index.ema50
            ):
                score -= 5.0

            if (
                index.ema200 > 0
                and price > index.ema200
            ):
                score += 5.0

            elif (
                index.ema200 > 0
                and price < index.ema200
            ):
                score -= 5.0

        # ---------------------------------------------
        # VWAP
        # ---------------------------------------------

        if (
            index.vwap > 0
            and price > 0
        ):

            if price > index.vwap:

                score += 5.0

            elif price < index.vwap:

                score -= 5.0

        # ---------------------------------------------
        # ADX BONUS
        # ---------------------------------------------

        if index.adx >= 25:

            if score > 0:

                score += 5.0

            elif score < 0:

                score -= 5.0

        return max(
            -100.0,
            min(
                100.0,
                score,
            ),
        )

    # =====================================================
    # BREADTH SCORE
    # =====================================================

    @staticmethod
    def _breadth_score(
        breadth: MarketBreadth,
    ) -> float:
        """
        Return market breadth score from -100 to +100.
        """

        score = 0.0

        total = (
            breadth.total_stocks
            or (
                breadth.advances
                + breadth.declines
                + breadth.unchanged
            )
        )

        if total <= 0:
            return 0.0

        advance_percent = (
            breadth.advances
            / total
            * 100.0
        )

        decline_percent = (
            breadth.declines
            / total
            * 100.0
        )

        # ---------------------------------------------
        # ADVANCE / DECLINE
        # ---------------------------------------------

        if advance_percent >= 70:

            score += 60.0

        elif advance_percent >= 60:

            score += 40.0

        elif advance_percent >= 55:

            score += 25.0

        elif decline_percent >= 70:

            score -= 60.0

        elif decline_percent >= 60:

            score -= 40.0

        elif decline_percent >= 55:

            score -= 25.0

        # ---------------------------------------------
        # NEW HIGH / LOW
        # ---------------------------------------------

        if (
            breadth.new_highs
            > breadth.new_lows
        ):

            score += 10.0

        elif (
            breadth.new_lows
            > breadth.new_highs
        ):

            score -= 10.0

        # ---------------------------------------------
        # 20 EMA BREADTH
        # ---------------------------------------------

        if breadth.above_20_ema > 0:

            above_percent = (
                breadth.above_20_ema
                / total
                * 100.0
            )

            if above_percent >= 65:

                score += 15.0

            elif above_percent <= 35:

                score -= 15.0

        # ---------------------------------------------
        # 50 EMA BREADTH
        # ---------------------------------------------

        if breadth.above_50_ema > 0:

            above_percent = (
                breadth.above_50_ema
                / total
                * 100.0
            )

            if above_percent >= 65:

                score += 10.0

            elif above_percent <= 35:

                score -= 10.0

        # ---------------------------------------------
        # 200 EMA BREADTH
        # ---------------------------------------------

        if breadth.above_200_ema > 0:

            above_percent = (
                breadth.above_200_ema
                / total
                * 100.0
            )

            if above_percent >= 65:

                score += 5.0

            elif above_percent <= 35:

                score -= 5.0

        return max(
            -100.0,
            min(
                100.0,
                score,
            ),
        )

    # =====================================================
    # VIX SCORE
    # =====================================================

    @staticmethod
    def _volatility_score(
        vix: float,
    ) -> float:
        """
        Return volatility intensity from 0 to 100.

        This is not bullish/bearish direction.
        """

        if vix <= 0:
            return 0.0

        if vix < 10:

            return 20.0

        if vix < 13:

            return 30.0

        if vix < 16:

            return 40.0

        if vix < 20:

            return 55.0

        if vix < 25:

            return 70.0

        if vix < 30:

            return 85.0

        return 100.0

    # =====================================================
    # DETERMINE TREND
    # =====================================================

    @staticmethod
    def _trend_from_score(
        score: float,
    ) -> MarketTrend:

        if score >= 65:

            return (
                MarketTrend.STRONG_BULLISH
            )

        if score >= 25:

            return (
                MarketTrend.BULLISH
            )

        if score <= -65:

            return (
                MarketTrend.STRONG_BEARISH
            )

        if score <= -25:

            return (
                MarketTrend.BEARISH
            )

        return (
            MarketTrend.SIDEWAYS
        )

    # =====================================================
    # DETERMINE BIAS
    # =====================================================

    @staticmethod
    def _bias_from_score(
        score: float,
    ) -> MarketBias:

        if score >= 65:

            return (
                MarketBias.STRONG_BULLISH
            )

        if score >= 25:

            return (
                MarketBias.BULLISH
            )

        if score <= -65:

            return (
                MarketBias.STRONG_BEARISH
            )

        if score <= -25:

            return (
                MarketBias.BEARISH
            )

        return (
            MarketBias.NEUTRAL
        )

    # =====================================================
    # MARKET REGIME
    # =====================================================

    @staticmethod
    def _determine_regime(
        directional_score: float,
        volatility_score: float,
    ) -> MarketRegime:

        absolute_direction = abs(
            directional_score
        )

        if volatility_score >= 85:

            return (
                MarketRegime.HIGH_VOLATILITY
            )

        if absolute_direction >= 70:

            return (
                MarketRegime.STRONG_TREND
            )

        if absolute_direction >= 35:

            return (
                MarketRegime.TRENDING
            )

        if (
            absolute_direction < 25
            and volatility_score < 70
        ):

            return (
                MarketRegime.RANGE_BOUND
            )

        if volatility_score <= 25:

            return (
                MarketRegime.LOW_VOLATILITY
            )

        return (
            MarketRegime.UNCERTAIN
        )

    # =====================================================
    # ANALYZE
    # =====================================================

    def analyze(
        self,
        context: ScannerContext,
    ) -> MarketContextResult:
        """
        Perform complete market analysis.
        """

        nifty_score = (
            self._index_direction_score(
                context.nifty
            )
        )

        bank_score = (
            self._index_direction_score(
                context.bank_nifty
            )
        )

        breadth_score = (
            self._breadth_score(
                context.breadth
            )
        )

        volatility_score = (
            self._volatility_score(
                context.india_vix
            )
        )

        # ---------------------------------------------
        # INDEX COMPOSITE
        # ---------------------------------------------

        if (
            context.nifty is not None
            and context.bank_nifty is not None
        ):

            index_score = (
                nifty_score * 0.65
                + bank_score * 0.35
            )

        elif context.nifty is not None:

            index_score = nifty_score

        elif context.bank_nifty is not None:

            index_score = bank_score

        else:

            index_score = 0.0

        # ---------------------------------------------
        # FINAL DIRECTION SCORE
        # ---------------------------------------------

        directional_score = (
            index_score * 0.70
            + breadth_score * 0.30
        )

        directional_score = max(
            -100.0,
            min(
                100.0,
                directional_score,
            ),
        )

        trend = (
            self._trend_from_score(
                directional_score
            )
        )

        bias = (
            self._bias_from_score(
                directional_score
            )
        )

        regime = (
            self._determine_regime(
                directional_score,
                volatility_score,
            )
        )

        strength = round(
            abs(directional_score),
            2,
        )

        bullish_score = round(
            max(
                directional_score,
                0.0,
            ),
            2,
        )

        bearish_score = round(
            abs(
                min(
                    directional_score,
                    0.0,
                )
            ),
            2,
        )

        # ---------------------------------------------
        # TRADE PERMISSION
        # ---------------------------------------------

        long_allowed = (
            trend
            != MarketTrend.STRONG_BEARISH
        )

        short_allowed = (
            trend
            != MarketTrend.STRONG_BULLISH
        )

        # Extremely high VIX:
        # allow scanners to run, but avoid declaring
        # unrestricted directional conditions.

        if volatility_score >= 100:

            if trend == MarketTrend.SIDEWAYS:

                long_allowed = False

                short_allowed = False

        # ---------------------------------------------
        # REASON
        # ---------------------------------------------

        reason = (

            f"Index={index_score:.1f}, "
            f"Breadth={breadth_score:.1f}, "
            f"VIX={context.india_vix:.2f}, "
            f"Direction={directional_score:.1f}"
        )

        return MarketContextResult(

            trend=trend,

            bias=bias,

            regime=regime,

            strength=strength,

            bullish_score=bullish_score,

            bearish_score=bearish_score,

            long_allowed=long_allowed,

            short_allowed=short_allowed,

            volatility_score=round(
                volatility_score,
                2,
            ),

            breadth_score=round(
                breadth_score,
                2,
            ),

            index_score=round(
                index_score,
                2,
            ),

            reason=reason,
        )

    # =====================================================
    # APPLY TO CONTEXT
    # =====================================================

    def update_context(
        self,
        context: ScannerContext,
    ) -> MarketContextResult:
        """
        Analyze market and update ScannerContext.
        """

        result = self.analyze(
            context
        )

        context.market_trend = (
            result.trend
        )

        context.market_strength = (
            result.strength
        )

        context.metadata[
            "market_bias"
        ] = result.bias.value

        context.metadata[
            "market_regime"
        ] = result.regime.value

        context.metadata[
            "long_allowed"
        ] = result.long_allowed

        context.metadata[
            "short_allowed"
        ] = result.short_allowed

        context.metadata[
            "market_analysis"
        ] = result.to_dict()

        context.touch()

        return result

    # =====================================================
    # SIGNAL CONFIRMATION
    # =====================================================

    def confirms_signal(
        self,
        signal_type: SignalType,
        context: ScannerContext,
    ) -> bool:
        """
        Check whether market direction supports signal.
        """

        result = self.analyze(
            context
        )

        if signal_type == SignalType.BUY:

            return result.long_allowed

        if signal_type == SignalType.SELL:

            return result.short_allowed

        return True

    # =====================================================
    # DIRECTION BONUS
    # =====================================================

    def signal_bonus(
        self,
        signal_type: SignalType,
        context: ScannerContext,
    ) -> float:
        """
        Return market-alignment bonus/penalty.

        Range:
        -10 to +10
        """

        result = self.analyze(
            context
        )

        strength_factor = min(
            result.strength / 100.0,
            1.0,
        )

        bonus = (
            10.0
            * strength_factor
        )

        if signal_type == SignalType.BUY:

            if result.trend in (
                MarketTrend.BULLISH,
                MarketTrend.STRONG_BULLISH,
            ):

                return round(
                    bonus,
                    2,
                )

            if result.trend in (
                MarketTrend.BEARISH,
                MarketTrend.STRONG_BEARISH,
            ):

                return round(
                    -bonus,
                    2,
                )

        elif signal_type == SignalType.SELL:

            if result.trend in (
                MarketTrend.BEARISH,
                MarketTrend.STRONG_BEARISH,
            ):

                return round(
                    bonus,
                    2,
                )

            if result.trend in (
                MarketTrend.BULLISH,
                MarketTrend.STRONG_BULLISH,
            ):

                return round(
                    -bonus,
                    2,
                )

        return 0.0


# =========================================================
# GLOBAL ANALYZER
# =========================================================

market_context_analyzer = (
    MarketContextAnalyzer()
)


# =========================================================
# CONVENIENCE FUNCTIONS
# =========================================================

def analyze_market_context(
    context: ScannerContext,
) -> MarketContextResult:
    """
    Analyze scanner market context.
    """

    return (
        market_context_analyzer
        .analyze(context)
    )


def update_market_context(
    context: ScannerContext,
) -> MarketContextResult:
    """
    Analyze and update scanner context.
    """

    return (
        market_context_analyzer
        .update_context(context)
    )


