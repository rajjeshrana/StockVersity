    # =====================================================
    # VALIDATE SCANNERS
    # =====================================================

    def validate_scanners(
        self,
    ) -> List[str]:

        errors: List[
            str
        ] = []

        for name, scanner in (
            self.scanners.items()
        ):

            if not isinstance(
                scanner,
                BaseScanner,
            ):

                errors.append(
                    f"{name} is not a BaseScanner."
                )

            if (
                scanner.name
                != name
            ):

                errors.append(
                    f"Scanner registry mismatch: "
                    f"{name} != {scanner.name}"
                )

        for name in (
            self.enabled_scanners
        ):

            if name not in self.scanners:

                errors.append(
                    f"Enabled scanner not registered: "
                    f"{name}"
                )

        return errors

