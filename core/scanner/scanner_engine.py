    # HIGH RISK ALERTS
    # =====================================================

    def high_risk_alerts(
        self,
        minimum_rr: float = 1.5,
    ) -> List[Dict[str, Any]]:

        alerts: List[
            Dict[str, Any]
        ] = []

        for signal in self.results:

            if (
                signal.risk_reward
                >= minimum_rr
            ):

                continue

            alert = self.create_alert(
                signal
            )

            alert[
                "warning"
            ] = "LOW_RISK_REWARD"

            alerts.append(
                alert
            )

        return alerts

    # =====================================================
    # NEAR ENTRY ALERTS
    # =====================================================

    def near_entry_alerts(
        self,
        tolerance: float = 0.25,
    ) -> List[Dict[str, Any]]:

        alerts: List[
            Dict[str, Any]
        ] = []

        tolerance = max(
            0.0,
            float(tolerance),
        )

        for signal in self.results:

            if signal.entry <= 0:

                continue

            difference = abs(
                signal.last_price
                - signal.entry
            )

            percentage = (
                difference
                / signal.entry
            ) * 100

            if (
                percentage
                <= tolerance
            ):

                alerts.append(
                    self.create_alert(
                        signal
                    )
                )

        return alerts

    # =====================================================
    # UNIQUE ALERTS
    # =====================================================

    def unique_alerts(
        self,
        alerts: List[Dict[str, Any]],
    ) -> List[Dict[str, Any]]:

        unique: Dict[
            str,
            Dict[str, Any],
        ] = {}

        for alert in alerts:

            symbol = str(
                alert.get(
                    "symbol",
                    "",
                )
            ).upper()

            if not symbol:

                continue

            existing = unique.get(
                symbol
            )

            if existing is None:

                unique[
                    symbol
                ] = alert

                continue

            if (
                alert.get(
                    "priority",
                    0,
                )
                >
                existing.get(
                    "priority",
                    0,
                )
            ):

                unique[
                    symbol
                ] = alert

        return sorted(
            unique.values(),
            key=lambda alert: (
                alert.get(
                    "priority",
                    0,
                )
            ),
            reverse=True,
        )

