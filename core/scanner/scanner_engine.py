"""
=========================================================
StockVersity Scanner Pro
Scanner Engine
Version : 2.1
=========================================================

File:
    core/scanner/scanner_engine.py

Purpose:
    Central execution and orchestration engine for all
    StockVersity scanners.

Responsibilities:
    • Scanner registration
    • Scanner enable / disable
    • Parallel execution
    • Sequential execution
    • Raw signal preservation
    • Duplicate signal merging
    • Multi-scanner consensus
    • Opportunity ranking
    • Market breadth
    • Market sentiment
    • Market health scoring
    • Sector ranking
    • Scanner ranking
    • Dashboard feeds
    • Alert generation
    • Filtering
    • Export
    • Diagnostics
"""

from __future__ import annotations

from concurrent.futures import (
    ThreadPoolExecutor,
    as_completed,
)

from datetime import datetime

from typing import (
    Any,
    Dict,
    Iterator,
    List,
    Optional,
)

from core.scanner.signal import Signal
from core.scanner.base_scanner import BaseScanner


# =========================================================
# ENGINE CONSTANTS
# =========================================================

ENGINE_NAME = "StockVersity Scanner Engine"

ENGINE_VERSION = "2.1"


# =========================================================
# SCANNER ENGINE
# =========================================================

class ScannerEngine:
    """
    Central StockVersity scanner execution engine.

    Architecture
    ------------

    Market Data
        ↓
    ScannerEngine
        ↓
    Enabled Scanners
        ↓
    Raw Signals
        ↓
    Consensus Analysis
        ↓
    Duplicate Merge
        ↓
    Ranking
        ↓
    Dashboard / Alerts
    """

    # =====================================================
    # INITIALIZATION
    # =====================================================

    def __init__(
        self,
        *,
        parallel: bool = True,
        max_workers: int = 8,
        debug: bool = False,
    ) -> None:

        # -------------------------------------------------
        # SCANNERS
        # -------------------------------------------------

        self.scanners: Dict[str, BaseScanner] = {}

        self.enabled_scanners: Dict[str, BaseScanner] = {}

        # -------------------------------------------------
        # RESULTS
        # -------------------------------------------------

        # Every signal generated by every scanner.
        # Duplicates are intentionally preserved here.
        self.raw_results: List[Signal] = []

        # Final merged / ranked results.
        self.results: List[Signal] = []

        # -------------------------------------------------
        # MARKET DATA
        # -------------------------------------------------

        self.market_data: Dict[str, Any] = {}

        # -------------------------------------------------
        # EXECUTION
        # -------------------------------------------------

        self.execution_started: Optional[datetime] = None

        self.execution_finished: Optional[datetime] = None

        self.execution_time: float = 0.0

        # -------------------------------------------------
        # CONFIGURATION
        # -------------------------------------------------

        self.parallel = bool(parallel)

        self.max_workers = max(
            1,
            int(max_workers),
        )

        self.debug = bool(debug)

    # =====================================================
    # REGISTER SCANNER
    # =====================================================

    def register(
        self,
        scanner: BaseScanner,
        *,
        enabled: bool = True,
    ) -> None:
        """
        Register one scanner.

        Scanner names must be unique.
        """

        if not isinstance(
            scanner,
            BaseScanner,
        ):

            raise TypeError(
                "scanner must inherit from BaseScanner"
            )

        scanner_name = scanner.name

        if not scanner_name:

            raise ValueError(
                "Scanner must have a valid name."
            )

        if scanner_name in self.scanners:

            raise ValueError(
                f"Scanner already registered: "
                f"{scanner_name}"
            )

        self.scanners[
            scanner_name
        ] = scanner

        if enabled:

            self.enabled_scanners[
                scanner_name
            ] = scanner

        self.log(
            "Registered scanner:",
            scanner_name,
        )

    # =====================================================
    # BULK REGISTER
    # =====================================================

    def register_many(
        self,
        scanners: List[BaseScanner],
        *,
        enabled: bool = True,
    ) -> None:
        """
        Register multiple scanners.
        """

        for scanner in scanners:

            self.register(
                scanner,
                enabled=enabled,
            )

    # =====================================================
    # UNREGISTER
    # =====================================================

    def unregister(
        self,
        scanner_name: str,
    ) -> None:
        """
        Remove scanner from engine.
        """

        self.scanners.pop(
            scanner_name,
            None,
        )

        self.enabled_scanners.pop(
            scanner_name,
            None,
        )

        self.log(
            "Unregistered scanner:",
            scanner_name,
        )

    # =====================================================
    # BULK UNREGISTER
    # =====================================================

    def unregister_many(
        self,
        scanner_names: List[str],
    ) -> None:

        for scanner_name in scanner_names:

            self.unregister(
                scanner_name
            )

    # =====================================================
    # GET SCANNER
    # =====================================================

    def get(
        self,
        scanner_name: str,
    ) -> Optional[BaseScanner]:

        return self.scanners.get(
            scanner_name
        )

    # =====================================================
    # HAS SCANNER
    # =====================================================

    def has_scanner(
        self,
        scanner_name: str,
    ) -> bool:

        return scanner_name in self.scanners

    # =====================================================
    # ENABLE SCANNER
    # =====================================================

    def enable(
        self,
        scanner_name: str,
    ) -> None:

        scanner = self.scanners.get(
            scanner_name
        )

        if scanner is None:

            raise KeyError(
                f"Scanner not registered: "
                f"{scanner_name}"
            )

        self.enabled_scanners[
            scanner_name
        ] = scanner

        self.log(
            "Enabled scanner:",
            scanner_name,
        )

    # =====================================================
    # DISABLE SCANNER
    # =====================================================

    def disable(
        self,
        scanner_name: str,
    ) -> None:

        self.enabled_scanners.pop(
            scanner_name,
            None,
        )

        self.log(
            "Disabled scanner:",
            scanner_name,
        )

    # =====================================================
    # ENABLE ALL
    # =====================================================

    def enable_all(
        self,
    ) -> None:

        self.enabled_scanners = dict(
            self.scanners
        )

    # =====================================================
    # DISABLE ALL
    # =====================================================

    def disable_all(
        self,
    ) -> None:

        self.enabled_scanners.clear()

    # =====================================================
    # RESET RESULTS
    # =====================================================

    def reset_results(
        self,
    ) -> None:
        """
        Clear scanner results without clearing
        current market data.
        """

        self.raw_results.clear()

        self.results.clear()

    # =====================================================
    # RESET
    # =====================================================

    def reset(
        self,
    ) -> None:
        """
        Reset runtime state.
        """

        self.reset_results()

        self.market_data = {}

        self.execution_started = None

        self.execution_finished = None

        self.execution_time = 0.0

    # =====================================================
    # RUN ENGINE
    # =====================================================

    def run(
        self,
        market_data: Dict[str, Any],
    ) -> List[Signal]:
        """
        Execute all enabled scanners.

        Parameters
        ----------
        market_data:
            Parsed market-data structure supplied
            by StockVersity market-data layer.

        Returns
        -------
        List[Signal]
            Final merged and ranked opportunities.
        """

        if market_data is None:

            raise ValueError(
                "market_data cannot be None"
            )

        self.reset_results()

        self.market_data = market_data

        self.execution_started = datetime.now()

        self.execution_finished = None

        self.execution_time = 0.0

        if not self.enabled_scanners:

            self.execution_finished = datetime.now()

            self.execution_time = (
                self.execution_finished
                - self.execution_started
            ).total_seconds()

            return []

        if (
            self.parallel
            and len(self.enabled_scanners) > 1
        ):

            self._run_parallel()

        else:

            self._run_sequential()

        # IMPORTANT:
        # raw_results remains untouched so consensus
        # can detect multiple scanners finding the
        # same symbol.

        self._merge_results()

        self.execution_finished = datetime.now()

        self.execution_time = (
            self.execution_finished
            - self.execution_started
        ).total_seconds()

        self.log(
            "Execution completed.",
            f"Raw signals={len(self.raw_results)}",
            f"Final signals={len(self.results)}",
            f"Time={self.execution_time:.3f}s",
        )

        return list(
            self.results
        )

    # =====================================================
    # SEQUENTIAL EXECUTION
    # =====================================================

    def _run_sequential(
        self,
    ) -> None:

        for scanner in self.enabled_scanners.values():

            try:

                signals = self._execute_scanner(
                    scanner
                )

                if signals:

                    self.raw_results.extend(
                        signals
                    )

            except Exception as exc:

                self.log(
                    "Scanner failed:",
                    scanner.name,
                    repr(exc),
                )

    # =====================================================
    # PARALLEL EXECUTION
    # =====================================================

    def _run_parallel(
        self,
    ) -> None:

        worker_count = min(
            self.max_workers,
            max(
                1,
                len(self.enabled_scanners),
            ),
        )

        with ThreadPoolExecutor(
            max_workers=worker_count
        ) as executor:

            futures = {

                executor.submit(
                    self._execute_scanner,
                    scanner,
                ): scanner

                for scanner
                in self.enabled_scanners.values()
            }

            for future in as_completed(
                futures
            ):

                scanner = futures[
                    future
                ]

                try:

                    signals = future.result()

                    if signals:

                        self.raw_results.extend(
                            signals
                        )

                except Exception as exc:

                    self.log(
                        "Scanner failed:",
                        scanner.name,
                        repr(exc),
                    )

    # =====================================================
    # EXECUTE ONE SCANNER
    # =====================================================

    def _execute_scanner(
        self,
        scanner: BaseScanner,
    ) -> List[Signal]:

        scanner_name = getattr(
            scanner,
            "name",
            type(scanner).__name__,
        )

        print(
            f"[SCANNER EXEC] {scanner_name} START "
            f"| market_data={len(self.market_data)}"
        )

        try:

            scanner.reset()

            signals = scanner.run(
                self.market_data
            )

            if signals is None:
                signals = []

            signals = list(
                signals
            )

            print(
                f"[SCANNER EXEC] {scanner_name} DONE "
                f"| signals={len(signals)}"
            )

            return signals

        except Exception as exc:

            print(
                f"[SCANNER EXEC] {scanner_name} FAILED "
                f"| {type(exc).__name__}: {exc}"
            )

            raise

    # =====================================================
    # MERGE RESULTS
    # =====================================================

    def _merge_results(
        self,
    ) -> None:
        """
        Merge duplicate symbols.

        The highest-quality signal for each symbol
        becomes the final dashboard signal.

        raw_results remains unchanged.
        """

        merged: Dict[str, Signal] = {}

        for signal in self.raw_results:

            symbol = signal.symbol.upper()

            existing = merged.get(
                symbol
            )

            if existing is None:

                merged[
                    symbol
                ] = signal

                continue

            current_quality = (
                signal.score,
                signal.confidence,
                signal.risk_reward,
            )

            existing_quality = (
                existing.score,
                existing.confidence,
                existing.risk_reward,
            )

            if (
                current_quality
                >
                existing_quality
            ):

                merged[
                    symbol
                ] = signal

        self.results = sorted(
            merged.values(),
            key=lambda signal: (
                signal.score,
                signal.confidence,
                signal.risk_reward,
            ),
            reverse=True,
        )

    # =====================================================
    # EXECUTION SUMMARY
    # =====================================================

    def execution_summary(
        self,
    ) -> Dict[str, Any]:

        return {

            "scanners": len(
                self.enabled_scanners
            ),

            "raw_signals": len(
                self.raw_results
            ),

            "signals": len(
                self.results
            ),

            "execution_time": round(
                self.execution_time,
                3,
            ),

            "parallel": self.parallel,

            "timestamp": datetime.now().isoformat(),

        }

    # =====================================================
    # SCANNER REPORTS
    # =====================================================

    def scanner_reports(
        self,
    ) -> List[Dict[str, Any]]:

        reports: List[
            Dict[str, Any]
        ] = []

        for scanner in (
            self.enabled_scanners.values()
        ):

            try:

                report = scanner.performance()

                reports.append(
                    report
                )

            except Exception as exc:

                reports.append(
                    {
                        "scanner": scanner.name,
                        "status": "FAILED",
                        "error": str(exc),
                    }
                )

        return reports

    # =====================================================
    # TOP OPPORTUNITIES
    # =====================================================

    def top_opportunities(
        self,
        count: int = 10,
    ) -> List[Signal]:

        count = max(
            0,
            int(count),
        )

        return self.results[
            :count
        ]

    # =====================================================
    # BUY SIGNALS
    # =====================================================

    def buy_signals(
        self,
    ) -> List[Signal]:

        return [
            signal
            for signal in self.results
            if signal.is_buy
        ]

    # =====================================================
    # SELL SIGNALS
    # =====================================================

    def sell_signals(
        self,
    ) -> List[Signal]:

        return [
            signal
            for signal in self.results
            if signal.is_sell
        ]

    # =====================================================
    # WATCH SIGNALS
    # =====================================================

    def watch_signals(
        self,
    ) -> List[Signal]:

        return [
            signal
            for signal in self.results
            if signal.is_watch
        ]

    # =====================================================
    # SCORE DISTRIBUTION
    # =====================================================

    def score_distribution(
        self,
    ) -> Dict[str, int]:

        distribution = {
            "90+": 0,
            "80-89": 0,
            "70-79": 0,
            "60-69": 0,
            "<60": 0,
        }

        for signal in self.results:

            score = signal.score

            if score >= 90:

                distribution[
                    "90+"
                ] += 1

            elif score >= 80:

                distribution[
                    "80-89"
                ] += 1

            elif score >= 70:

                distribution[
                    "70-79"
                ] += 1

            elif score >= 60:

                distribution[
                    "60-69"
                ] += 1

            else:

                distribution[
                    "<60"
                ] += 1

        return distribution

    # =====================================================
    # CONFIDENCE DISTRIBUTION
    # =====================================================

    def confidence_distribution(
        self,
    ) -> Dict[str, int]:

        distribution = {
            "90+": 0,
            "80-89": 0,
            "70-79": 0,
            "<70": 0,
        }

        for signal in self.results:

            confidence = signal.confidence

            if confidence >= 90:

                distribution[
                    "90+"
                ] += 1

            elif confidence >= 80:

                distribution[
                    "80-89"
                ] += 1

            elif confidence >= 70:

                distribution[
                    "70-79"
                ] += 1

            else:

                distribution[
                    "<70"
                ] += 1

        return distribution

    # =====================================================
    # PATTERN DISTRIBUTION
    # =====================================================

    def pattern_distribution(
        self,
    ) -> Dict[str, int]:

        patterns: Dict[
            str,
            int,
        ] = {}

        for signal in self.results:

            pattern = signal.pattern.value

            patterns[
                pattern
            ] = (
                patterns.get(
                    pattern,
                    0,
                )
                + 1
            )

        return dict(
            sorted(
                patterns.items(),
                key=lambda item: item[1],
                reverse=True,
            )
        )

    # =====================================================
    # SECTOR DISTRIBUTION
    # =====================================================

    def sector_distribution(
        self,
    ) -> Dict[str, int]:

        sectors: Dict[
            str,
            int,
        ] = {}

        for signal in self.results:

            sector = (
                signal.sector
                or "UNKNOWN"
            )

            sectors[
                sector
            ] = (
                sectors.get(
                    sector,
                    0,
                )
                + 1
            )

        return dict(
            sorted(
                sectors.items(),
                key=lambda item: item[1],
                reverse=True,
            )
        )

    # =====================================================
    # MARKET BREADTH
    # =====================================================

    def market_breadth(
        self,
    ) -> Dict[str, Any]:
        """
        Breadth based on final generated signals.
        """

        buys = len(
            self.buy_signals()
        )

        sells = len(
            self.sell_signals()
        )

        watches = len(
            self.watch_signals()
        )

        directional_total = (
            buys + sells
        )

        if directional_total == 0:

            bullish = 0.0

            bearish = 0.0

        else:

            bullish = round(
                (
                    buys
                    / directional_total
                )
                * 100,
                2,
            )

            bearish = round(
                (
                    sells
                    / directional_total
                )
                * 100,
                2,
            )

        return {

            "buy": buys,

            "sell": sells,

            "watch": watches,

            "bullish_percent": bullish,

            "bearish_percent": bearish,

            "net_breadth": buys - sells,

        }

    # =====================================================
    # MARKET SENTIMENT
    # =====================================================

    def market_sentiment(
        self,
    ) -> str:

        breadth = self.market_breadth()

        bullish = breadth[
            "bullish_percent"
        ]

        directional_total = (
            breadth["buy"]
            + breadth["sell"]
        )

        if directional_total == 0:

            return "NEUTRAL"

        if bullish >= 75:

            return "STRONG_BULLISH"

        if bullish >= 60:

            return "BULLISH"

        if bullish <= 25:

            return "STRONG_BEARISH"

        if bullish <= 40:

            return "BEARISH"

        return "NEUTRAL"

    # =====================================================
    # MARKET HEALTH SCORE
    # =====================================================

    def market_health_score(
        self,
    ) -> float:
        """
        Composite market-quality score from 0 to 100.

        NOTE:
        This measures scanner opportunity quality.
        It is not intended to replace true NSE breadth.
        """

        if not self.results:

            return 0.0

        average_score = sum(
            signal.score
            for signal in self.results
        ) / len(
            self.results
        )

        average_confidence = sum(
            signal.confidence
            for signal in self.results
        ) / len(
            self.results
        )

        breadth = self.market_breadth()

        bullish = breadth[
            "bullish_percent"
        ]

        health = (
            average_score * 0.45
            + average_confidence * 0.35
            + bullish * 0.20
        )

        return round(
            max(
                0.0,
                min(
                    health,
                    100.0,
                ),
            ),
            2,
        )

    # =====================================================
    # SECTOR RANKING
    # =====================================================

    def sector_ranking(
        self,
    ) -> List[Dict[str, Any]]:

        ranking: Dict[
            str,
            Dict[str, Any],
        ] = {}

        for signal in self.results:

            sector = (
                signal.sector
                or "UNKNOWN"
            )

            if sector not in ranking:

                ranking[
                    sector
                ] = {
                    "sector": sector,
                    "signals": 0,
                    "_score_total": 0.0,
                    "_confidence_total": 0.0,
                }

            item = ranking[
                sector
            ]

            item[
                "signals"
            ] += 1

            item[
                "_score_total"
            ] += signal.score

            item[
                "_confidence_total"
            ] += signal.confidence

        rows: List[
            Dict[str, Any]
        ] = []

        for item in ranking.values():

            count = item[
                "signals"
            ]

            rows.append(
                {
                    "sector": item[
                        "sector"
                    ],
                    "signals": count,
                    "average_score": round(
                        item[
                            "_score_total"
                        ]
                        / count,
                        2,
                    ),
                    "average_confidence": round(
                        item[
                            "_confidence_total"
                        ]
                        / count,
                        2,
                    ),
                }
            )

        rows.sort(
            key=lambda row: (
                row[
                    "average_score"
                ],
                row[
                    "average_confidence"
                ],
                row[
                    "signals"
                ],
            ),
            reverse=True,
        )

        return rows

    # =====================================================
    # SCANNER RANKING
    # =====================================================

    def scanner_ranking(
        self,
    ) -> List[Dict[str, Any]]:

        ranking: List[
            Dict[str, Any]
        ] = []

        for scanner in (
            self.enabled_scanners.values()
        ):

            try:

                report = scanner.performance()

            except Exception:

                report = {}

            ranking.append(
                {
                    "scanner": scanner.name,
                    "signals": report.get(
                        "signals_found",
                        0,
                    ),
                    "average_score": report.get(
                        "average_score",
                        0,
                    ),
                    "average_rr": report.get(
                        "average_rr",
                        0,
                    ),
                    "execution_time": report.get(
                        "execution_time",
                        0,
                    ),
                }
            )

        ranking.sort(
            key=lambda row: (
                row[
                    "average_score"
                ],
                row[
                    "signals"
                ],
            ),
            reverse=True,
        )

        return ranking

    # =====================================================
    # MULTI-SCANNER CONSENSUS
    # =====================================================

    def consensus(
        self,
    ) -> List[Dict[str, Any]]:
        """
        Group RAW signals by symbol.

        This is intentionally based on raw_results rather
        than final results so multiple scanner detections
        are preserved.
        """

        grouped: Dict[
            str,
            List[Signal],
        ] = {}

        for signal in self.raw_results:

            symbol = signal.symbol.upper()

            grouped.setdefault(
                symbol,
                [],
            ).append(
                signal
            )

        consensus_rows: List[
            Dict[str, Any]
        ] = []

        for symbol, signals in (
            grouped.items()
        ):

            scanners = sorted(
                {
                    signal.scanner_name
                    for signal in signals
                }
            )

            buy_count = sum(
                1
                for signal in signals
                if signal.is_buy
            )

            sell_count = sum(
                1
                for signal in signals
                if signal.is_sell
            )

            watch_count = sum(
                1
                for signal in signals
                if signal.is_watch
            )

            if (
                buy_count > sell_count
                and buy_count > 0
            ):

                direction = "BUY"

            elif (
                sell_count > buy_count
                and sell_count > 0
            ):

                direction = "SELL"

            else:

                direction = "MIXED"

            consensus_rows.append(
                {
                    "symbol": symbol,

                    "scanner_count": len(
                        scanners
                    ),

                    "signal_count": len(
                        signals
                    ),

                    "scanners": scanners,

                    "direction": direction,

                    "buy_count": buy_count,

                    "sell_count": sell_count,

                    "watch_count": watch_count,

                    "best_score": max(
                        signal.score
                        for signal in signals
                    ),

                    "average_score": round(
                        sum(
                            signal.score
                            for signal in signals
                        )
                        / len(signals),
                        2,
                    ),

                    "best_confidence": max(
                        signal.confidence
                        for signal in signals
                    ),

                    "average_confidence": round(
                        sum(
                            signal.confidence
                            for signal in signals
                        )
                        / len(signals),
                        2,
                    ),

                    "best_rr": max(
                        signal.risk_reward
                        for signal in signals
                    ),
                }
            )

        consensus_rows.sort(
            key=lambda row: (
                row[
                    "scanner_count"
                ],
                row[
                    "best_score"
                ],
                row[
                    "best_confidence"
                ],
            ),
            reverse=True,
        )

        return consensus_rows

    # =====================================================
    # CONSENSUS SIGNALS
    # =====================================================

    def consensus_signals(
        self,
        minimum_scanners: int = 2,
    ) -> List[Dict[str, Any]]:

        minimum_scanners = max(
            1,
            int(minimum_scanners),
        )

        return [
            row
            for row in self.consensus()
            if row[
                "scanner_count"
            ] >= minimum_scanners
        ]

    # =====================================================
    # CONSENSUS LOOKUP
    # =====================================================

    def consensus_for_symbol(
        self,
        symbol: str,
    ) -> Optional[Dict[str, Any]]:

        symbol = symbol.upper()

        for row in self.consensus():

            if row[
                "symbol"
            ] == symbol:

                return row

        return None

    # =====================================================
    # PRIORITY SCORE
    # =====================================================

    def priority_score(
        self,
        signal: Signal,
    ) -> float:
        """
        Unified StockVersity opportunity score.

        Components
        ----------
        Signal quality      : 45%
        Confidence          : 30%
        Risk / Reward       : 15%
        Relative volume     : 10%
        """

        rr_component = (
            min(
                max(
                    signal.risk_reward,
                    0.0,
                ),
                5.0,
            )
            / 5.0
            * 100.0
        )

        volume_component = (
            min(
                max(
                    signal.volume_ratio,
                    0.0,
                ),
                5.0,
            )
            / 5.0
            * 100.0
        )

        priority = (
            signal.score * 0.45
            + signal.confidence * 0.30
            + rr_component * 0.15
            + volume_component * 0.10
        )

        return round(
            max(
                0.0,
                min(
                    priority,
                    100.0,
                ),
            ),
            2,
        )

