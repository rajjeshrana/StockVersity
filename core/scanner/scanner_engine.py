    # =====================================================
    # BUILD ALERT QUEUE
    # =====================================================

    def build_alert_queue(
        self,
        minimum_score: float = 85.0,
        minimum_confidence: float = 0.0,
    ) -> List[Dict[str, Any]]:

        queue: List[
            Dict[str, Any]
        ] = []

        for signal in (
            self.priority_ranking(
                len(
                    self.results
                )
            )
        ):

            if (
                signal.score
                < minimum_score
            ):

                continue

            if (
                signal.confidence
                < minimum_confidence
            ):

                continue

            queue.append(
                self.create_alert(
                    signal
                )
            )

        return self.unique_alerts(
            queue
        )

